    var symbolName: String {
        switch self {
        case .systemAccent: return "apple.logo"
        case .space: return "moon.stars.fill"
        case .galaxy: return "sparkles"
        case .aurora: return "mountain.2.fill"
        case .custom: return "paintpalette.fill"
